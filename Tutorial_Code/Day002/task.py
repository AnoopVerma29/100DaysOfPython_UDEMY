# Subscripting
print("Hellp"[0])  # H
print("Hello"[4])  # o  
# Negative indexing
print("Hello"[-1])  # o 
print("Hello"[-2])  # l

# String slicing
print("Hello"[0:3])  # Hel  
print("Hello"[1:4])  # ell
print("Hello"[:3])   # Hel
print("Hello"[2:5])  # llo

print("123" + "456")  # 123456 Concatination    
print("123" * 3)      # 123123123

# Integer
print(123 + 456)  # 579
print(123 * 3)    # 369 

# Large integers
print(123_456_789)  # 123456789

# Float = floating point number
print(3.14159)  # 3.14159
print(3.14 * 2)  # 6.28

# Boolean - Two possible values: True or False
print(True)   # True
print(False)  # False

print(len("Hello"))  # 5
print(type("Hello"))  # <class 'str'>
print(type(123))      # <class 'int'>
print(type(3.14))     # <class 'float'>
print(type(True))     # <class 'bool'>

# Type conversion, called Type Casting
print(int("123"))    # 123
print(float("123"))  # 123.0
print(str(123))      # "123"
print(bool(0))      # False
print(bool(1))      # True
print(int("123") + int("456"))  # 579
print(float("123") + float("456"))  # 579.0
print(str(123) + str(456))  # "123456"

